#!/usr/bin/env python3
"""Compile the finite, authored facade fixture list; --check verifies the output."""
import argparse
import json
import math
import subprocess
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    source=json.loads((ROOT/'crates/vearth-gen/assets/cities/signs.json').read_text())
    rows=['// Generated by tools/build_city_signs.py from the authored facade catalog.',
          'use super::Fixture;', 'pub(super) const FIXTURES: &[Fixture] = &[']
    for district in source['districts']:
        for f in district['fixtures']:
            assert district.get('query_half_extent_m') == 240.0, 'fixtures require detailed source surveys'
            assert 0 < int(f['seed']) < 2**64
            assert all(math.isfinite(f[k]) for k in ('lat','lon','width','height','bottom'))
            assert abs(f['lat']-district['lat']) < .02 and abs(f['lon']-district['lon']) < .02
            assert len(f['aim']) == 2 and all(math.isfinite(v) for v in f['aim']) and math.hypot(*f['aim']) > 0
            assert f['width']>0 and f['height']>0 and f['bottom']>=0
            assert f['design'] in range(5)
            assert len(f['color'])==3 and all(0<=c<=255 for c in f['color'])
            rows.extend(['Fixture {',f'seed:{f["seed"]}, lat:{f["lat"]}, lon:{f["lon"]},',
                f'width:{float(f["width"])}, height:{float(f["height"])}, bottom:{float(f["bottom"])},',
                f'color:{list(f["color"])}, design:{f["design"]}, outward:{list(map(float,f["aim"]))},', '},'])
    rows.append('];')
    result=subprocess.run(['rustfmt','--edition','2024'],input=('\n'.join(rows)+'\n').encode(),capture_output=True,check=True).stdout
    path=ROOT/'crates/vearth-gen/src/building_surface/city_fixtures/generated.rs'
    if args.check:
        assert path.read_bytes()==result,'authored city fixture output is stale'
    else:
        path.parent.mkdir(parents=True,exist_ok=True);path.write_bytes(result)

if __name__=='__main__':main()
