#!/usr/bin/env python3
"""Bake compact optical masks from the pinned OSM sources; no network at build/run time."""

import argparse
import gzip
import hashlib
import json
import math
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "crates/vearth-gen/assets/water"
OUTPUT = ROOT / "crates/vearth-gen/src/water_catalog_data.rs"
RADIUS_M = 6_371_008.8


def rings_from_source(source, metadata):
    elements = {(e["type"], e["id"]): e for e in source["elements"]}
    feature = elements[metadata["osm_type"], metadata["osm_id"]]
    assert feature["version"] == metadata["version"]
    assert feature["tags"]["natural"] == "water"
    if feature["type"] == "way":
        paths = [feature["nodes"]]
    else:
        assert feature["tags"]["type"] == "multipolygon"
        paths = []
        for role in ["outer", "inner"]:
            pending = [elements["way", m["ref"]]["nodes"][:]
                       for m in feature["members"] if m["role"] == role]
            while pending:
                path = pending.pop(0)
                while path[-1] != path[0]:
                    for index, other in enumerate(pending):
                        if path[-1] == other[-1]:
                            other = other[::-1]
                        if path[-1] == other[0]:
                            path.extend(other[1:])
                            pending.pop(index)
                            break
                    else:
                        raise ValueError("unclosed OSM member chain")
                paths.append(path)
    assert paths and all(len(p) >= 4 and p[0] == p[-1] for p in paths)
    return [[(elements["node", n]["lon"], elements["node", n]["lat"])
             for n in path] for path in paths]


def distance(point, a, b):
    dx, dy = b[0] - a[0], b[1] - a[1]
    denominator = dx * dx + dy * dy
    t = max(0.0, min(1.0, ((point[0] - a[0]) * dx + (point[1] - a[1]) * dy)
                    / denominator)) if denominator else 0.0
    return math.hypot(point[0] - a[0] - t * dx, point[1] - a[1] - t * dy)


def simplify(path, tolerance):
    if len(path) <= 2:
        return path
    error, index = max((distance(p, path[0], path[-1]), i)
                       for i, p in enumerate(path[1:-1], 1))
    if error <= tolerance:
        return [path[0], path[-1]]
    return simplify(path[:index + 1], tolerance)[:-1] + simplify(path[index:], tolerance)


def bake():
    manifest = json.loads((ASSETS / "catalog.json").read_text())
    lines = ["// Generated by tools/build-water-catalog.py; edit crates/vearth-gen/assets/water/catalog.json.",
             "// Geometry © OpenStreetMap contributors, ODbL 1.0. See crates/vearth-gen/assets/water/README.md.",
             "use super::Entry;", "pub(super) static ENTRIES: &[Entry] = &["]
    for entry in manifest["entries"]:
        metadata = entry["source"]
        payload = gzip.decompress((ASSETS / metadata["path"]).read_bytes())
        assert hashlib.sha256(payload).hexdigest() == metadata["sha256"]
        source_rings = rings_from_source(json.loads(payload), metadata)
        lat, lon = entry["anchor_degrees"]
        sx = RADIUS_M * math.pi / 180 * math.cos(math.radians(lat))
        sy = RADIUS_M * math.pi / 180
        rings = []
        for ring in source_rings:
            projected = [((x - lon) * sx, (y - lat) * sy) for x, y in ring]
            # Splitting the closed ring avoids the degenerate endpoint chord.
            split = max(range(len(projected)), key=lambda i: math.dist(projected[0], projected[i]))
            reduced = (simplify(projected[:split + 1], entry["simplify_m"])[:-1]
                       + simplify(projected[split:], entry["simplify_m"])[:-1])
            if len(reduced) < 3:
                reduced = projected[:-1]
            # Reject any simplification that exceeds the declared error budget.
            segments = list(zip(reduced, reduced[1:] + reduced[:1]))
            assert all(min(distance(p, a, b) for a, b in segments) <= entry["simplify_m"] + 1e-6
                       for p in projected)
            rings.append(reduced)
        points = [p for ring in rings for p in ring]
        bounds = [min(p[0] for p in points), min(p[1] for p in points),
                  max(p[0] for p in points), max(p[1] for p in points)]
        # A spherical anchor suffices for the conservative chord-distance gate.
        a, b = math.radians(lat), math.radians(lon)
        anchor = [math.cos(a) * math.cos(b), math.cos(a) * math.sin(b), math.sin(a)]
        radius = max(math.hypot(*p) for p in points) + entry["margin_m"] + entry["fade_m"]
        def array(values):
            return "[" + ", ".join(f"{value:.8f}" for value in values) + "]"
        lines.extend(["Entry {", f'name: {json.dumps(entry["name"], ensure_ascii=False)},',
                      f"origin_deg: {array([lat, lon])},", f"metres_per_degree: {array([sy, sx])},",
                      f"anchor: {array(anchor)},", f"radius_m: {radius:.3f},",
                      f"bounds_m: {array(bounds)},", f'margin_m: {entry["margin_m"]:.1f},',
                      f'fade_m: {entry["fade_m"]:.1f},',
                      f'bottom: {array(entry["bottom_srgb"])},',
                      f'body: {array(entry["body_srgb"])},',
                      f'alternate: {array(entry["alternate_srgb"])},',
                      f'extinction: {array(entry["extinction_per_m"])},',
                      f'variation_scale_m: {entry["variation_scale_m"]:.1f},',
                      "rings: &["])
        for ring in rings:
            lines.append("&[" + ", ".join(array(point) for point in ring) + "],")
        lines.extend(["],", "},"])
    lines.append("];\n")
    result = subprocess.run(["rustfmt", "--edition", "2024"], input="\n".join(lines),
                            text=True, capture_output=True, check=True)
    return result.stdout


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generated = bake()
    if args.check:
        if OUTPUT.read_text() != generated:
            raise SystemExit("water catalog differs; run tools/build-water-catalog.py")
    else:
        OUTPUT.write_text(generated)
    print("Water catalog: pinned hashes, closed rings, simplification bounds and generated data verified.")
