#!/usr/bin/env python3
"""Bake original metric heritage models and their geographic runtime catalog.

Run without filters for the complete 52-site pack; --check verifies every byte.
--only accepts site or group names for incremental authoring. Source records
carry dependencies and evidence hashes as well as output hashes.
"""
import argparse
import importlib
import json
from pathlib import Path
import struct
import subprocess
import zlib

import numpy as np

from build_city_catalog import encode, digest, rust_float
from heritage_catalog.inventory import GROUPS, NAMES
from heritage_catalog.materials import validate_runtime_ids

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'tools/heritage_catalog'
OUTPUT = ROOT / 'crates/vearth-gen/assets/landmarks/heritage-surfaces'
REGISTRY = ROOT / 'crates/vearth-gen/src/landmarks/heritage_generated.rs'


def registry(entries):
    rust = ['// Generated by tools/build_heritage_catalog.py.',
            'use super::{Base, Landmark, Suppress, TerrainFlatten};',
            'use super::heritage::TerrainCut;',
            'pub(super) const HERITAGE_MODELS: &[Landmark] = &[']
    for e in entries:
        base = 'Base::Terrain' if e['base'] == 'terrain' else f'Base::Fixed({rust_float(e["base"])})'
        suppression = e.get('suppress_bbox')
        suppression = 'None' if suppression is None else f'Some(({list(map(float, suppression[0]))}, {list(map(float, suppression[1]))}))'
        rust.extend(['Landmark {', f'name: "{e["name"]}",',
            f'lat_deg:{rust_float(e["lat"])}, lon_deg:{rust_float(e["lon"])}, heading_deg:{rust_float(e["heading"])},',
            f'base:{base}, bbox_min:{e["bbox_min"]}, bbox_max:{e["bbox_max"]},',
            'suppress:Suppress {' + ', '.join(f'{k}:{str(e["suppress_"+k]).lower()}' for k in ['buildings', 'roads', 'trees']) + '},',
            f'suppress_bbox_xz:{suppression},', '},'])
    rust.append('];')
    rust.extend(["pub(super) fn terrain_flatten(name: &str) -> &'static [TerrainFlatten] {", 'match name {'])
    for e in entries:
        patches = e.get('terrain_flatten', [])
        if not patches:
            continue
        rust.append('"' + e['name'] + '" => &[')
        for p in patches:
            fixed = p.get('fixed_base_geo')
            fixed = 'None' if fixed is None else 'Some(' + rust_float(fixed) + ')'
            rust.append('TerrainFlatten {'
                + 'center_xz:' + str(list(map(float, p['center_xz']))) + ','
                + 'half_extent:' + str(list(map(float, p['half_extent']))) + ','
                + 'feather_m:' + rust_float(p['feather_m']) + ','
                + 'sample_clearance_m:' + rust_float(p['sample_clearance_m']) + ','
                + 'fixed_base_geo:' + fixed + ',},')
        rust.append('],')
    rust.extend(['_ => &[],', '}', '}'])
    rust.extend(['pub(super) fn max_source_building_span(name: &str) -> Option<f64> {', 'match name {'])
    for e in entries:
        if e.get('max_source_building_span_m') is not None:
            rust.append('"' + e['name'] + '" => ' + 'Some(' + rust_float(e['max_source_building_span_m']) + '),' )
    rust.extend(['_ => None,', '}', '}'])
    rust.extend(["pub(super) fn source_exclusion_polygons(name: &str) -> Option<&'static [&'static [[f64; 2]]]> {", 'match name {'])
    for e in entries:
        if e.get('source_exclusion_polygons') is not None:
            rust.append('"' + e['name'] + '" => Some(&[' + ','.join('&' + repr([list(map(float,v)) for v in p]) for p in e['source_exclusion_polygons']) + ']),')
    rust.extend(['_ => None,', '}', '}'])
    for field in ('terrain_cuts', 'water_cuts', 'terrain_grades'):
        rust.extend(["pub(super) fn " + field + "(name: &str) -> &'static [TerrainCut] {", 'match name {'])
        for e in entries:
            if e.get(field):
                rust.append('"' + e['name'] + '" => &[')
                for p in e[field]:
                    rust.append('TerrainCut { polygon: &' + repr([list(map(float,v)) for v in p['polygon_xz']])
                        + ', plane: ' + repr(list(map(float, p['plane'])))
                        + ', feather_m: ' + rust_float(p['feather_m']) + '},')
                rust.append('],')
        rust.extend(['_ => &[],', '}', '}'])
    rust.extend(['#[cfg(not(target_arch = "wasm32"))]', "pub(super) fn bytes(name: &str) -> Option<(&'static str, &'static [u8])> {", 'match name {'])
    for e in entries:
        name = e['name']
        rust.append(f'"{name}" => Some(("{name}",vearth_platform::asset_bytes!("../../assets/landmarks/heritage-surfaces/{name}.lms"))),')
    rust.extend(['_ => None,', '}', '}'])
    rust.extend(["pub(super) fn road_exclusion_polygons(name: &str) -> Option<&'static [&'static [[f64; 2]]]> {", 'match name {'])
    for e in entries:
        if e.get('road_exclusion_polygons') is not None:
            rust.append('"' + e['name'] + '" => Some(&[' + ','.join('&' + repr([list(map(float,v)) for v in p]) for p in e['road_exclusion_polygons']) + ']),')
    rust.extend(['_ => None,', '}', '}'])
    return subprocess.run(['rustfmt', '--edition', '2024'], input=('\n'.join(rust)+'\n').encode(), capture_output=True, check=True).stdout


def bake(module, entry):
    validate_runtime_ids()
    name = entry['name']
    assert np.isfinite([entry['lat'], entry['lon'], entry['heading']]).all(), name
    assert abs(entry['lat']) <= 85 and abs(entry['lon']) <= 180, name
    assert entry['base'] == 'terrain' or np.isfinite(float(entry['base'])), name
    assert entry.get('references'), f'{name}: reference evidence is required'
    assert not entry.get('water_cuts') or entry['base'] != 'terrain', f'{name}: water requires a fixed datum'
    if entry.get('terrain_grades'):
        assert entry['base'] != 'terrain' and not entry.get('terrain_flatten'), f'{name}: independent grades require a fixed model datum without terrain_flatten'
    if entry.get('terrain_cuts') or entry.get('terrain_flatten') or entry.get('terrain_grades'):
        patches = entry.get('terrain_flatten', [])
        assert all(p.get('fixed_base_geo') is not None for p in patches), f'{name}: terrain correction requires fixed patch datums'
        assert entry['base'] != 'terrain' or patches, f'{name}: terrain correction requires a clean datum'
    levels, stats, points = [], [], []
    for lod in range(3):
        data, stat, p = encode(module.build(name, lod))
        assert 0 < stat['triangles'] <= 500_000, (name, lod, stat)
        assert not stats or stat['triangles'] <= stats[-1]['triangles'], (name, 'LOD grows')
        levels.append(data)
        stats.append(stat)
        points.append(p)
    raw = b'LMS1' + struct.pack('<I', 3) + b''.join(levels)
    assert len(raw) <= 256 * 1024 * 1024, (name, 'decode budget')
    payload = struct.pack('<I', len(raw)) + zlib.compress(raw, 9)
    p = np.concatenate(points).astype(np.float64)
    low = np.round(np.floor(p.min(axis=0)*10)/10-.2, 1)
    high = np.round(np.ceil(p.max(axis=0)*10)/10+.2, 1)
    pad = float(entry.get('activation_pad', 0))
    assert np.isfinite(pad) and pad >= 0, name
    low[[0, 2]] -= pad
    high[[0, 2]] += pad
    if entry.get('activation_bounds_xz') is not None:
        a = np.asarray(entry['activation_bounds_xz'], float)
        assert a.shape == (2, 2) and np.isfinite(a).all() and (a[1] > a[0]).all(), name
        low[[0, 2]] = np.minimum(low[[0, 2]], a[0])
        high[[0, 2]] = np.maximum(high[[0, 2]], a[1])
    for patch in entry.get('terrain_flatten', []):
        center = np.asarray(patch['center_xz'], float)
        half = np.asarray(patch['half_extent'], float)
        feather = float(patch['feather_m'])
        clearance = float(patch['sample_clearance_m'])
        assert center.shape == half.shape == (2,) and np.isfinite(center).all(), name
        assert np.isfinite(half).all() and (half > 0).all(), name
        assert np.isfinite([feather, clearance]).all() and feather > 0 and clearance >= 0, name
        assert patch.get('fixed_base_geo') is None or np.isfinite(patch['fixed_base_geo']), name
        low[[0, 2]] = np.minimum(low[[0, 2]], center-half-feather)
        high[[0, 2]] = np.maximum(high[[0, 2]], center+half+feather)
    for cut in entry.get('terrain_cuts', []) + entry.get('water_cuts', []) + entry.get('terrain_grades', []):
        ring = np.asarray(cut['polygon_xz'], float)
        assert np.isfinite(cut['plane']).all() and len(cut['plane']) == 3, name
        feather = float(cut['feather_m'])
        assert np.isfinite(feather) and feather > 0, name
        low[[0, 2]] = np.minimum(low[[0, 2]], ring.min(axis=0)-feather)
        high[[0, 2]] = np.maximum(high[[0, 2]], ring.max(axis=0)+feather)
    polygons = (entry.get('road_exclusion_polygons', [])
                + entry.get('source_exclusion_polygons', [])
                + [cut['polygon_xz'] for cut in entry.get('terrain_cuts', []) + entry.get('water_cuts', []) + entry.get('terrain_grades', [])])
    for polygon in polygons:
        ring = np.asarray(polygon, float)
        assert ring.ndim == 2 and ring.shape[1] == 2 and len(ring) >= 3 and np.isfinite(ring).all(), name
        d = np.roll(ring, -1, axis=0)-ring
        q = np.roll(d, -1, axis=0)
        cross = d[:, 0]*q[:, 1]-d[:, 1]*q[:, 0]
        assert (cross > 1e-8).all() or (cross < -1e-8).all(), (name, 'non-convex road footprint')
        assert (ring >= low[[0, 2]]).all() and (ring <= high[[0, 2]]).all(), name
    dependencies = [Path(module.__file__), Path(__file__), ROOT/'tools/build_city_catalog.py',
                    ROOT/'tools/city_catalog/common.py', ROOT/'tools/city_catalog/expansion_heritage.py']
    dependencies.extend(module.__dict__.get('DEPENDENCIES', []))
    dependencies.extend(SOURCE.glob('geometry.py'))
    dependencies.extend(SOURCE.glob('materials.py'))
    dependencies.extend(path for path in (SOURCE/'references'/module.__name__.split('.')[-1]).rglob('*')
                        if '__pycache__' not in path.parts and path.suffix not in ('.pyc', '.pyo'))
    dependencies = sorted(set(p for p in dependencies if p.is_file()))
    record = {**entry, 'bbox_min':low.tolist(), 'bbox_max':high.tolist(), 'levels':stats,
        'geometry':'original metric geometry authored for Low Poly Earth from cited architectural references',
        'license':'repository LICENSE; reference images and plans are not embedded textures',
        'source':str(Path(module.__file__).relative_to(ROOT)),
        'dependencies':{str(p.relative_to(ROOT)):digest(p.read_bytes()) for p in dependencies},
        'output_sha256':digest(payload)}
    return payload, record


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--only', nargs='+', choices=(*NAMES, *GROUPS))
    args = parser.parse_args()
    selected = set(NAMES) if not args.only else {n for value in args.only for n in GROUPS.get(value, (value,))}
    outputs = {}
    records = {}
    for group, expected in GROUPS.items():
        wanted = set(expected) & selected
        if not wanted:
            continue
        module = importlib.import_module('heritage_catalog.'+group)
        entries = {e['name']:e for e in module.ENTRIES}
        assert len(entries) == len(module.ENTRIES) and not set(entries)-set(expected), group
        assert not wanted-set(entries), f'missing sites in {group}: {sorted(wanted-set(entries))}'
        for name in expected:
            if name not in wanted:
                continue
            payload, record = bake(module, entries[name])
            outputs[OUTPUT/(name+'.lms')] = payload
            outputs[OUTPUT/(name+'.source.json')] = (json.dumps(record, indent=2)+'\n').encode()
            records[name] = record
            print(name, record['levels'], flush=True)
    for name in NAMES:
        path = OUTPUT/(name+'.source.json')
        if name not in records and path.exists():
            record = json.loads(path.read_text())
            mesh = OUTPUT/(name+'.lms')
            assert mesh.exists() and digest(mesh.read_bytes()) == record['output_sha256'], name
            records[name] = record
    entries = [records[n] for n in NAMES if n in records]
    if not args.only:
        assert len(entries) == len(set(NAMES)) == 52
    outputs[REGISTRY] = registry(entries)
    outputs[OUTPUT/'catalog.json'] = (json.dumps(entries, indent=2)+'\n').encode()
    for path, data in outputs.items():
        if args.check:
            if not path.exists() or path.read_bytes() != data:
                raise SystemExit(f'stale generated asset: {path.relative_to(ROOT)}')
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)


if __name__ == '__main__':
    main()
